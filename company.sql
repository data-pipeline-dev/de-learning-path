-- =====================================================
-- 1. СТВОРЕННЯ СХЕМИ
-- =====================================================

DROP SCHEMA IF EXISTS company CASCADE;
CREATE SCHEMA company;

SET search_path TO company;
-- =====================================================
-- 2. ТАБЛИЦЯ DEPARTMENTS
-- =====================================================

CREATE TABLE company.departments (
    id INTEGER PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);


-- =====================================================
-- 3. ТАБЛИЦЯ EMPLOYEES
-- =====================================================

CREATE TABLE company.employees (
    id INTEGER PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    department_id INTEGER,
    manager_id INTEGER,
    salary NUMERIC(12,2) NOT NULL,
    hired_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_employees_department
        FOREIGN KEY (department_id)
        REFERENCES company.departments(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_employees_manager
        FOREIGN KEY (manager_id)
        REFERENCES company.employees(id)
        ON DELETE SET NULL,

    CONSTRAINT chk_employees_salary
        CHECK (salary >= 0)
);


-- =====================================================
-- 4. ТАБЛИЦЯ CUSTOMERS
-- =====================================================

CREATE TABLE company.customers (
    id INTEGER PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    registered_at TIMESTAMP NOT NULL
);


-- =====================================================
-- 5. ТАБЛИЦЯ ORDERS
-- =====================================================

CREATE TABLE company.orders (
    id INTEGER PRIMARY KEY,
    customer_id INTEGER NOT NULL,
    employee_id INTEGER NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES company.customers(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_orders_employee
        FOREIGN KEY (employee_id)
        REFERENCES company.employees(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_orders_amount
        CHECK (amount >= 0)
);


-- =====================================================
-- 6. ТАБЛИЦЯ LOGINS
-- =====================================================

CREATE TABLE company.logins (
    user_id INTEGER NOT NULL,
    logged_at TIMESTAMP NOT NULL,

    CONSTRAINT pk_logins
        PRIMARY KEY (user_id, logged_at),

    CONSTRAINT fk_logins_employee
        FOREIGN KEY (user_id)
        REFERENCES company.employees(id)
        ON DELETE CASCADE
);


-- =====================================================
-- 7. ІНДЕКСИ
-- =====================================================

CREATE INDEX idx_employees_department
    ON company.employees(department_id);

CREATE INDEX idx_employees_manager
    ON company.employees(manager_id);

CREATE INDEX idx_orders_customer
    ON company.orders(customer_id);

CREATE INDEX idx_orders_employee
    ON company.orders(employee_id);

CREATE INDEX idx_orders_created_at
    ON company.orders(created_at);

CREATE INDEX idx_logins_logged_at
    ON company.logins(logged_at);


